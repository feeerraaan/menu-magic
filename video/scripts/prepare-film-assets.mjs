// Converts video/public/film/*.png (2x captures from
// scripts/capture-film-shots.mjs) into JPEGs the renderer can afford, and writes
// video/src/shots.ts with each shot's CSS coordinate space.
//
// The PNGs stay as the source of truth. Remotion loads the JPEGs through
// staticFile() rather than as data URIs: on a 3.8 GB box the bundle must not
// carry every capture at once, and Chrome only decodes the images a given frame
// actually paints.

import { execSync } from 'node:child_process';
import { readdirSync, statSync, writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { join, resolve, basename } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const src = join(root, 'public', 'film');
const out = join(root, 'public', 'shots');
mkdirSync(out, { recursive: true });

const pngSize = (file) => {
  const d = readFileSync(file).subarray(16, 24);
  return { w: d.readUInt32BE(0), h: d.readUInt32BE(4) };
};

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const files = readdirSync(src).filter((f) => f.endsWith('.png')).sort();
const entries = [];

for (const f of files) {
  const from = join(src, f);
  const name = basename(f, '.png');
  const to = join(out, `${name}.jpg`);
  const { w, h } = pngSize(from);
  // The captures are 2x (deviceScaleFactor 2 desktop, 3 phone). Keeping them at
  // 2x CSS gives the camera room to push to 1.5x zoom and stay sharp.
  const isPhone = w === 1290;
  const cssW = isPhone ? 430 : w / 2;
  const cssH = isPhone ? Math.round(h / 3) : h / 2;
  const targetW = Math.min(w, cssW * 2);
  execSync(
    `ffmpeg -y -loglevel error -i ${JSON.stringify(from)} -vf "scale=${targetW}:-2:flags=lanczos" -q:v 3 ${JSON.stringify(to)}`,
  );
  const kb = Math.round(statSync(to).size / 1024);
  entries.push({ name, cssW, cssH, kb });
  console.log(`${f.padEnd(24)} ${w}x${h} -> ${targetW}px jpg ${kb} KB   (page ${cssW}x${cssH})`);
}

let ts = `// Generated by scripts/prepare-film-assets.mjs. Do not edit by hand.
//
// Every shot carries the CSS pixel size of the viewport it was captured in.
// That is the coordinate space the camera keyframes and the click targets in
// targets.json are expressed in, so the choreography stays readable as
// "pan to 1044,255" instead of carrying device pixel ratios around.

import { staticFile } from 'remotion';

export type Shot = {
  /** staticFile path to the JPEG. */
  src: string;
  /** Page width in CSS pixels: the x range of camera and target coordinates. */
  cw: number;
  /** Page height in CSS pixels. */
  ch: number;
};

const shot = (name: string, cw: number, ch: number): Shot => ({
  src: staticFile(\`shots/\${name}.jpg\`),
  cw,
  ch,
});

export const SHOTS = {
`;
for (const e of entries) {
  ts += `  ${camel(e.name)}: shot('${e.name}', ${e.cssW}, ${e.cssH}),\n`;
}
ts += `};

export type ShotName = keyof typeof SHOTS;
`;

writeFileSync(join(root, 'src', 'shots.ts'), ts);
console.log(`\n${entries.length} shots, ${entries.reduce((a, b) => a + b.kb, 0)} KB total`);
console.log('src/shots.ts written');
